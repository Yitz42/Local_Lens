// Builds public/hospital-ownership.js from an export of the PE Hospital Tracker (a shared Airtable view).
// Usage: node scripts/build-hospitals.mjs rows.json
// rows.json is an array of row objects keyed by the tracker's column names. Only hospitals the tracker
// lists as currently private equity backed, or as for-profit with a named parent system, are kept.
import {readFileSync,writeFileSync} from 'node:fs';
import {hospitalKey,cityKey} from '../public/hospital-match.js';

const [input]=process.argv.slice(2);
if(!input)throw new Error('Usage: node scripts/build-hospitals.mjs rows.json');
const rows=JSON.parse(readFileSync(input,'utf8'));
const text=value=>String(value??'').replace(/\s+/g,' ').trim();
const nameCounts=new Map();
for(const row of rows){const key=hospitalKey(row.Name);if(key)nameCounts.set(key,(nameCounts.get(key)||0)+1);}
const parents=[],firms=[],realEstate=[];
const indexOf=(list,value)=>{if(!value)return -1;let i=list.indexOf(value);if(i<0){i=list.length;list.push(value);}return i;};
const kept=[],seen=new Set();
for(const row of rows){
 const pe=text(row['Currently PE?'])==='Y',parent=text(row['Parent System/Company']),forProfit=/^(proprietary|for profit)$/i.test(text(row['Hospital Ownership']));
 if(!pe&&!(forProfit&&parent))continue;
 const key=hospitalKey(row.Name),city=cityKey(row.City),state=text(row.State).toUpperCase();
 if(!key||!state)continue;
 const id=key+'|'+city+'|'+state;if(seen.has(id))continue;seen.add(id);
 const jv=text(row['JV or Partnership']);
 kept.push([key,city,state,text(row['Facility ID (CCN)']),pe?1:0,indexOf(parents,parent),pe?indexOf(firms,text(row['PE Firm(s)'])):-1,indexOf(realEstate,text(row['Real Estate Ownership'])),jv?1:0,nameCounts.get(key)===1?1:0]);
}
kept.sort((a,b)=>a[0].localeCompare(b[0])||a[2].localeCompare(b[2])||a[1].localeCompare(b[1]));
const out=`// Generated by scripts/build-hospitals.mjs from the PE Hospital Tracker. Do not edit this file.
// This facility list comes from a third-party tracker and is not covered by the CC0 dedication in LICENSE-DATA.md.
export const HOSPITAL_TRACKER={url:'https://airtable.com/appd2resSxUkpguFP/shrojR480lmH8vKpu/tbl058jjL6qNMqzkM',title:'PE Hospital Tracker',checked:'2026-10-30'};
export const PARENTS=${JSON.stringify(parents)};
export const FIRMS=${JSON.stringify(firms)};
export const REAL_ESTATE=${JSON.stringify(realEstate)};
// [name key, city key, state, CMS certification number, currently PE (1/0), parent index, PE firms index,
//  real estate owner index, joint venture (1/0), name unique among all tracked hospitals (1/0)]
export const HOSPITALS=[
${kept.map(row=>JSON.stringify(row)).join(',\n')}
];
`;
writeFileSync(new URL('../public/hospital-ownership.js',import.meta.url),out);
console.log(`Hospitals: ${kept.length} kept (${kept.filter(r=>r[4]).length} private equity, ${kept.filter(r=>!r[4]).length} for-profit corporate) of ${rows.length} rows.`);
